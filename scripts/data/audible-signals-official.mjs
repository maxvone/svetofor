export function buildAudibleGroups() {
  return Object.entries(audibleOfficial).map(([id, meta]) => ({
    id,
    category: 'audible_signals',
    title_ru: meta.title_ru,
    title_en: meta.title_en,
    icon: meta.icon,
    itemCount: meta.items.length,
    summary_ru: meta.summary_ru,
    items: meta.items,
  }));
}
