export function buildSignsGroups() {
  return Object.entries(signsOfficial).map(([id, meta]) => ({
    id,
    category: 'signs_and_indications',
    title_ru: meta.title_ru,
    title_en: meta.title_en,
    icon: meta.icon,
    itemCount: meta.items.length,
    summary_ru: meta.summary_ru,
    items: meta.items,
  }));
}
