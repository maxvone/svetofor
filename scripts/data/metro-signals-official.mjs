/** Metro signals — Инструкция по сигнализации на метрополитенах РФ (МА «Метро»). */

export const REGULATION =
  'Инструкция по сигнализации на метрополитенах РФ (Международная Ассоциация «Метро», согласовано с ПТЭ)';

const R = REGULATION;

function item(groupId, suffix, title_ru, text, regulationRef) {
  return {
    id: `${groupId}-${suffix}`,
    title_ru,
    shortDescription_ru: text,
    fullDescription_ru: text,
    regulationRef,
  };
}

