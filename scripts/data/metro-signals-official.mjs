export function buildMetroSignalsGroups() {
  return Object.entries(metroSignalsOfficial).map(([id, meta]) => ({
    id,
    category: 'metro_signals',
    title_ru: meta.title_ru,
    title_en: meta.title_en,
    icon: meta.icon,
    itemCount: meta.items.length,
    summary_ru: meta.summary_ru,
    items: meta.items,
  }));
}
