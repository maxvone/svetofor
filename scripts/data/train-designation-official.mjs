export function buildTrainDesignationGroups() {
  return Object.entries(trainDesignationOfficial).map(([id, meta]) => ({
    id,
    category: 'train_designation',
    title_ru: meta.title_ru,
    title_en: meta.title_en,
    icon: meta.icon,
    itemCount: meta.items.length,
    summary_ru: meta.summary_ru,
    items: meta.items,
  }));
}
