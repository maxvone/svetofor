export function buildHandSignalsGroups() {
  return Object.entries(handSignalsOfficial).map(([id, meta]) => ({
    id,
    category: 'hand_signals',
    title_ru: meta.title_ru,
    title_en: meta.title_en,
    icon: meta.icon,
    itemCount: meta.items.length,
    summary_ru: meta.summary_ru,
    items: meta.items,
  }));
}
