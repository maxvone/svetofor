export function buildFoulProtectionGroups() {
  return Object.entries(foulProtectionOfficial).map(([id, meta]) => ({
    id,
    category: 'foul_protection',
    title_ru: meta.title_ru,
    title_en: meta.title_en,
    icon: meta.icon,
    itemCount: meta.items.length,
    summary_ru: meta.summary_ru,
    items: meta.items,
  }));
}
