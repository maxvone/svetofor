interface LucideIconByNameProps {
  name: string;
  size?: number;
  color?: string;
  strokeWidth?: number;
}

export function LucideIconByName({ name, size = 22, color = '#FFFFFF', strokeWidth = 2 }: LucideIconByNameProps) {
  const Icon = iconMap[name] ?? Circle;
  return <Icon size={size} color={color} strokeWidth={strokeWidth} />;
}
